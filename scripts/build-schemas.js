/**
 * Build JSON Schema artifacts from the YAML sources in schemata/.
 *
 * Outputs:
 * - schema/<name>.json: one JSON Schema document per source file
 * - schema/schemas.js: an ES module exporting all schemas, for runtime loading
 *   without filesystem access (also usable in browsers)
 *
 * Replaces the old grunt-yaml build step. Run via `npm run build`.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { load } from "js-yaml";

const schemataDir = join(import.meta.dirname, "..", "schemata");
const schemaDir = join(import.meta.dirname, "..", "schema");

const files = (await readdir(schemataDir))
  .filter((f) => f.endsWith(".yaml"))
  .sort();

/** @type {Record<string, object>} */
const schemas = {};
for (const file of files) {
  const name = file.replace(/\.yaml$/, "");
  const source = await readFile(join(schemataDir, file), "utf-8");
  const doc = /** @type {object} */ (load(source));
  schemas[name] = doc;

  const jsonDest = join(schemaDir, `${name}.json`);
  await writeFile(jsonDest, `${JSON.stringify(doc, null, 2)}\n`);
  console.log(`built schema/${name}.json`);
}

const jsDest = join(schemaDir, "schemas.js");
const jsSource = `// Generated by scripts/build-schemas.js from schemata/*.yaml. Do not edit.\nexport default ${JSON.stringify(schemas, null, 2)};\n`;
await writeFile(jsDest, jsSource);
console.log("built schema/schemas.js");
